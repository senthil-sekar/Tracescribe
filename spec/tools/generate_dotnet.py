#!/usr/bin/env python3
"""Generate C# constants from spec/attributes.yaml.

Usage:
    python3 spec/tools/generate_dotnet.py           # write the generated file
    python3 spec/tools/generate_dotnet.py --check   # exit 1 if it is out of date

Requires PyYAML (pip install pyyaml).
"""
from __future__ import annotations

import argparse
import re
import sys
from html import escape
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
SPEC = ROOT / "spec" / "attributes.yaml"
OUT = ROOT / "dotnet" / "src" / "Tracescribe.SemanticConventions" / "TracescribeConventions.g.cs"


def pascal(name: str) -> str:
    parts = [p for p in re.split(r"[._\-]", name) if p]
    return "".join(p[:1].upper() + p[1:] for p in parts)


def strip_ns(identifier: str, ns: str) -> str:
    prefix = ns + "."
    return identifier[len(prefix):] if identifier.startswith(prefix) else identifier


def e(text: str | None) -> str:
    """Escape spec prose for XML doc comments."""
    return escape(" ".join((text or "").split()), quote=False)


def doc(xml: str, indent: str, entry: dict | None = None) -> str:
    """Emit a summary comment; xml must already be escaped. With an entry, adds its note and stability as remarks."""
    text = f"{indent}/// <summary>{xml}</summary>\n"
    if entry is not None:
        remarks = []
        if entry.get("note"):
            remarks.append(e(entry["note"]))
        if entry["stability"] == "development":
            remarks.append("Development: may change in a minor version.")
        if remarks:
            text += f"{indent}/// <remarks>{' '.join(remarks)}</remarks>\n"
    return text


STABILITIES = {"stable", "development"}


def check_stability(spec: dict) -> None:
    """Every attribute, event, event attribute and metric must declare a known stability."""
    entries = list(spec["attributes"]) + list(spec.get("metrics", []))
    for event in spec.get("events", []):
        entries.append(event)
        entries.extend(event.get("attributes", []))
    for entry in entries:
        name = entry.get("id") or entry.get("name")
        if entry.get("stability") not in STABILITIES:
            raise SystemExit(f"spec/attributes.yaml: '{name}' needs stability: stable or development")


def literal(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def generate(spec: dict) -> str:
    ns = spec["namespace"]
    lines: list[str] = []
    w = lines.append

    w("// <auto-generated>\n")
    w("// Generated by spec/tools/generate_dotnet.py from spec/attributes.yaml. Do not edit.\n")
    w("// </auto-generated>\n\n")
    w("namespace Tracescribe.SemanticConventions;\n\n")

    # Attributes
    w(doc("Attribute names defined by the Tracescribe semantic conventions.", ""))
    w("public static class TracescribeAttributes\n{\n")
    w(doc("Version of the conventions this SDK emits.", "    "))
    w(f"    public const string SchemaVersionValue = {literal(str(spec['schema_version']))};\n\n")
    w(doc("Prefix shared by every Tracescribe attribute.", "    "))
    w(f"    public const string Prefix = {literal(ns + '.')};\n")
    enums: list[dict] = []
    for attr in spec["attributes"]:
        attr_id = attr["id"]
        name = pascal(strip_ns(attr_id, ns))
        w("\n")
        if attr["type"].startswith("template"):
            w(doc(f"Prefix for <c>{attr_id}.&lt;key&gt;</c> attributes. {e(attr.get('brief'))}", "    ", attr))
            w(f"    public const string {name}Prefix = {literal(attr_id + '.')};\n\n")
            w(doc(f"Builds a <c>{attr_id}.&lt;key&gt;</c> attribute name.", "    "))
            w(f"    public static string {name}(string key) => {name}Prefix + key;\n")
            continue
        w(doc(f"<c>{attr_id}</c>: {e(attr.get('brief'))}", "    ", attr))
        w(f"    public const string {name} = {literal(attr_id)};\n")
        if attr["type"] == "enum":
            enums.append(attr)
    w("}\n\n")

    # Events
    w(doc("Event names and event attribute names.", ""))
    w("public static class TracescribeEvents\n{\n")
    first = True
    for event in spec.get("events", []):
        if not first:
            w("\n")
        first = False
        w(doc(f"Event <c>{event['name']}</c>: {e(event.get('brief'))}", "    ", event))
        w(f"    public const string {pascal(strip_ns(event['name'], ns))} = {literal(event['name'])};\n")
        for attr in event.get("attributes", []):
            w("\n")
            w(doc(f"<c>{attr['id']}</c>: {e(attr.get('brief'))}", "    ", attr))
            w(f"    public const string {pascal(strip_ns(attr['id'], ns))} = {literal(attr['id'])};\n")
    w("}\n")

    # Enum values
    for attr in enums:
        cls = pascal(strip_ns(attr["id"], ns)) + "Values"
        w("\n")
        w(doc(f"Allowed values of <c>{attr['id']}</c>.", ""))
        w(f"public static class {cls}\n{{\n")
        for i, member in enumerate(attr["members"]):
            if i:
                w("\n")
            w(doc(e(member.get("brief")), "    "))
            w(f"    public const string {pascal(member['value'])} = {literal(member['value'])};\n")
        w("}\n")

    # Metrics
    w("\n")
    w(doc("Metric instrument names and units.", ""))
    w("public static class TracescribeMetrics\n{\n")
    w(doc("Name of the <c>System.Diagnostics.Metrics.Meter</c> Tracescribe emits on.", "    "))
    w(f"    public const string MeterName = {literal(spec['meter_name'])};\n")
    for metric in spec.get("metrics", []):
        name = pascal(strip_ns(metric["name"], ns))
        w("\n")
        w(doc(f"<c>{metric['name']}</c> ({metric['instrument']}): {e(metric.get('brief'))} Attributes: {', '.join(metric.get('attributes', []))}.", "    ", metric))
        w(f"    public const string {name} = {literal(metric['name'])};\n\n")
        w(doc(f"Unit of <c>{metric['name']}</c>.", "    "))
        w(f"    public const string {name}Unit = {literal(metric['unit'])};\n")
    w("}\n")
    return "".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="fail if the generated file is out of date")
    args = parser.parse_args()

    spec = yaml.safe_load(SPEC.read_text(encoding="utf-8"))
    check_stability(spec)
    code = generate(spec)
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != code:
            print(f"{OUT.relative_to(ROOT)} is out of date. Run: python3 spec/tools/generate_dotnet.py", file=sys.stderr)
            return 1
        print("Generated constants are up to date.")
        return 0

    OUT.write_text(code, encoding="utf-8", newline="\n")
    print(f"Wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
